-- Notifications (M0-09): UnifiedPush endpoints per session, instance secrets (VAPID keys), per-type muting (FND-051, FND-052).

-- One Web Push endpoint per session; the keys encrypt messages (RFC 8291). Revoking a session deletes its row.
CREATE TABLE push_registration (
  session_id uuid PRIMARY KEY REFERENCES session(id) ON DELETE CASCADE,
  household_id uuid NOT NULL REFERENCES household(id),
  member_id uuid NOT NULL REFERENCES member(id),
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth text NOT NULL,
  -- Device UI language ('en', 'ru') for notification texts.
  language text NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);
CREATE INDEX push_registration_household ON push_registration (household_id);
CREATE INDEX push_registration_member ON push_registration (member_id);

-- Secrets generated by the server itself, e.g. the VAPID key pair ('vapid.public', 'vapid.private').
-- Kept in the database because the container file system is ephemeral.
CREATE TABLE instance_secret (
  name text PRIMARY KEY,
  value text NOT NULL
);

-- Muted notification types per member; absent row = not muted. `type` is NotificationType's wire name.
CREATE TABLE notification_setting (
  member_id uuid NOT NULL REFERENCES member(id) ON DELETE CASCADE,
  type text NOT NULL,
  muted boolean NOT NULL,
  PRIMARY KEY (member_id, type)
);
