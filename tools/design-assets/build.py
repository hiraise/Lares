#!/usr/bin/env python3
"""Generates the bundled design assets of the client (ADR-0016, visual-style.md).

- Manrope static instances 400/500/600/700/800 -> composeResources/font/manrope_<weight>.ttf
- Material Symbols Outlined at wght=250, opsz=24, GRAD=0 (FILL 0 and 1), every glyph named in icons.txt
  -> composeResources/drawable/ic_<name>.xml and ic_<name>_filled.xml (Android vector drawables, 24 dp)

Run by hand from any directory: `python3 tools/design-assets/build.py` (needs `pip install fonttools`).
Downloads are cached in tools/design-assets/.cache; outputs are committed.
"""

import sys
import urllib.request
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# Pinned sources (commit hashes); update both the hash and README.md when upgrading.
GOOGLE_FONTS_COMMIT = "e7db6ca603fd4862010383ff17ffd6cc4ffac1c0"
SYMBOLS_COMMIT = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
MANROPE_URL = f"https://raw.githubusercontent.com/google/fonts/{GOOGLE_FONTS_COMMIT}/ofl/manrope/Manrope%5Bwght%5D.ttf"
SYMBOLS_BASE = (
    f"https://raw.githubusercontent.com/google/material-design-icons/{SYMBOLS_COMMIT}"
    "/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D"
)
SYMBOLS_URL = SYMBOLS_BASE + ".ttf"
CODEPOINTS_URL = SYMBOLS_BASE + ".codepoints"

MANROPE_WEIGHTS = [400, 500, 600, 700, 800]
ICON_AXES = {"wght": 250, "opsz": 24, "GRAD": 0}

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RESOURCES = ROOT / "client/shared/src/commonMain/composeResources"
CACHE = HERE / ".cache"


def download(url: str, name: str) -> Path:
    CACHE.mkdir(exist_ok=True)
    target = CACHE / name
    if not target.exists():
        print(f"Downloading {url}")
        with urllib.request.urlopen(url) as response:
            target.write_bytes(response.read())
    return target


def build_fonts() -> None:
    source = download(MANROPE_URL, "Manrope[wght].ttf")
    out_dir = RESOURCES / "font"
    out_dir.mkdir(parents=True, exist_ok=True)
    for weight in MANROPE_WEIGHTS:
        font = instantiateVariableFont(TTFont(source), {"wght": weight}, updateFontNames=False)
        font.save(out_dir / f"manrope_{weight}.ttf")
        print(f"font/manrope_{weight}.ttf")


def icon_names() -> list[str]:
    names = []
    for line in (HERE / "icons.txt").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.append(line)
    return names


def format_number(value: float) -> str:
    # One decimal in a 960 viewport is far below a pixel and keeps the files small.
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def vector_xml(path_data: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/design-assets/build.py from Material Symbols Outlined (Apache 2.0). Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="960"\n'
        '    android:viewportHeight="960">\n'
        "    <path\n"
        '        android:fillColor="#FF000000"\n'
        f'        android:pathData="{path_data}" />\n'
        "</vector>\n"
    )


def build_icons() -> None:
    source = download(SYMBOLS_URL, "MaterialSymbolsOutlined.ttf")
    codepoints_file = download(CODEPOINTS_URL, "MaterialSymbolsOutlined.codepoints")
    codepoints = {}
    for line in codepoints_file.read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            codepoints[parts[0]] = int(parts[1], 16)
    names = icon_names()
    missing = [n for n in names if n not in codepoints]
    if missing:
        sys.exit(f"Unknown icon names in icons.txt: {', '.join(missing)}")

    out_dir = RESOURCES / "drawable"
    out_dir.mkdir(parents=True, exist_ok=True)
    for fill, suffix in [(0, ""), (1, "_filled")]:
        font = instantiateVariableFont(TTFont(source), {**ICON_AXES, "FILL": fill})
        upem = font["head"].unitsPerEm
        cmap = font.getBestCmap()
        glyphs = font.getGlyphSet()
        for name in names:
            pen = SVGPathPen(glyphs, ntos=format_number)
            # Font y grows upwards from the baseline; vector y grows downwards: flip inside the em square.
            glyphs[cmap[codepoints[name]]].draw(TransformPen(pen, (1, 0, 0, -1, 0, upem)))
            path = pen.getCommands()
            if not path:
                sys.exit(f"Empty glyph: {name}")
            (out_dir / f"ic_{name}{suffix}.xml").write_text(vector_xml(path))
    print(f"{len(names)} icons x 2 into drawable/")


if __name__ == "__main__":
    build_fonts()
    build_icons()
